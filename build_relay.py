"""Writes assets/relay.js from DISCORD_WEBHOOK_URL in .env.

GitHub Pages can't keep secrets, so the commission form posts to Discord straight
from the visitor's browser. The URL is scrambled (XOR + base64, reversed) so it isn't
sitting in the repo or page as plain text and leak scanners don't flag it. This is
obfuscation, not security: anyone determined can recover it. If the webhook gets
abused, delete it in Discord, make a new one, put it in .env and run this again:

    python build_relay.py
"""
import base64
import os
import secrets

ROOT = os.path.dirname(os.path.abspath(__file__))
url = ""
for line in open(os.path.join(ROOT, ".env"), encoding="utf-8"):
    if line.startswith("DISCORD_WEBHOOK_URL="):
        url = line.split("=", 1)[1].strip()
if not url.startswith("https://"):
    raise SystemExit("DISCORD_WEBHOOK_URL is missing from .env")

key = secrets.token_bytes(16)
mixed = bytes(b ^ key[i % len(key)] for i, b in enumerate(url.encode()))
blob = base64.b64encode(mixed).decode()[::-1]
k = base64.b64encode(key).decode()[::-1]
js = f"""// Generated by build_relay.py — do not edit. Scrambled form relay (see README).
window.Relay = (() => {{
  const d = (s) => Uint8Array.from(atob(s.split("").reverse().join("")), (c) => c.charCodeAt(0));
  const k = d("{k}"), b = d("{blob}");
  return () => new TextDecoder().decode(b.map((x, i) => x ^ k[i % k.length]));
}})();
"""
open(os.path.join(ROOT, "assets", "relay.js"), "w", encoding="utf-8", newline="\n").write(js)
assert "webhooks" not in js and "discord" not in js.lower().replace("// generated", "")
print("assets/relay.js written")
